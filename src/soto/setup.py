"""`soto setup`: vendor ComfyUI + ComfyUI-GGUF and fetch the small model pieces."""

from __future__ import annotations

import shutil
import subprocess
import sys

from soto import config


def _run(cmd: list[str], cwd=None) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def _clone_or_checkout(url: str, dest, commit: str) -> None:
    if dest.exists():
        print(f"  {dest.name}: already present, fetching {commit[:10]}...")
        _run(["git", "fetch", "--depth", "1", "origin", commit], cwd=dest)
        _run(["git", "checkout", commit], cwd=dest)
    else:
        print(f"  {dest.name}: cloning...")
        dest.parent.mkdir(parents=True, exist_ok=True)
        _run(["git", "clone", url, str(dest)])
        _run(["git", "checkout", commit], cwd=dest)


def clone_vendor_repos() -> None:
    print("Vendoring ComfyUI + ComfyUI-GGUF...")
    _clone_or_checkout(config.COMFYUI_REPO_URL, config.COMFYUI_DIR, config.COMFYUI_COMMIT)
    _clone_or_checkout(
        config.COMFYUI_GGUF_REPO_URL, config.COMFYUI_GGUF_DIR, config.COMFYUI_GGUF_COMMIT
    )


def write_extra_model_paths() -> None:
    path = config.COMFYUI_DIR / "extra_model_paths.yaml"
    content = f"""\
# Generated by `soto setup` -- points ComfyUI at this repo's models/ directory
# so downloaded checkpoints are used in place, not copied into vendor/ComfyUI.
soto:
  base_path: {config.REPO_ROOT}
  diffusion_models: models/
  vae: models/vae/
  text_encoders: models/text_encoders/
"""
    path.write_text(content)
    print(f"  wrote {path}")


def download_small_weights() -> None:
    from huggingface_hub import hf_hub_download

    config.MODELS_DIR.mkdir(parents=True, exist_ok=True)
    config.VAE_DIR.mkdir(parents=True, exist_ok=True)
    config.TEXT_ENCODERS_DIR.mkdir(parents=True, exist_ok=True)

    for spec in config.MODELS.values():
        if spec.remote_path is None:
            continue  # already present (e.g. the pre-downloaded 14B GGUF checkpoints)
        unet_path = config.MODELS_DIR / spec.filename
        if not unet_path.exists():
            print(f"  downloading {spec.filename}...")
            downloaded = hf_hub_download(repo_id=config.UNET_REPO, filename=spec.remote_path)
            shutil.copy(downloaded, unet_path)
        else:
            print(f"  {spec.filename}: already present")

    vae_path = config.VAE_DIR / config.VAE_FILENAME
    if not vae_path.exists():
        print(f"  downloading {config.VAE_FILENAME}...")
        downloaded = hf_hub_download(
            repo_id=config.VAE_REPO, filename=config.VAE_REMOTE_PATH
        )
        shutil.copy(downloaded, vae_path)
    else:
        print(f"  {config.VAE_FILENAME}: already present")

    text_encoder_path = config.TEXT_ENCODERS_DIR / config.TEXT_ENCODER_FILENAME
    if not text_encoder_path.exists():
        print(f"  downloading {config.TEXT_ENCODER_FILENAME}...")
        downloaded = hf_hub_download(
            repo_id=config.TEXT_ENCODER_REPO, filename=config.TEXT_ENCODER_REMOTE_PATH
        )
        shutil.copy(downloaded, text_encoder_path)
    else:
        print(f"  {config.TEXT_ENCODER_FILENAME}: already present")


def download_subject_models() -> None:
    """The depth and segmentation models `expand` finds the subject with, and
    the model it captions the clip with."""
    from huggingface_hub import snapshot_download

    for repo, path in ((config.DEPTH_MODEL_REPO, config.DEPTH_MODEL_DIR),
                       (config.SEGMENT_MODEL_REPO, config.SEGMENT_MODEL_DIR),
                       (config.CAPTION_MODEL_REPO, config.CAPTION_MODEL_DIR)):
        if (path / "config.json").is_file():
            print(f"  {path.name}: already present")
            continue
        print(f"  downloading {repo}...")
        snapshot_download(repo, local_dir=path)


def download_flux_models() -> None:
    """FLUX.1 Fill and its text encoders and VAE, for `expand`."""
    from huggingface_hub import hf_hub_download

    for repo, remote, dest in (
        (config.FLUX_FILL_REPO, config.FLUX_FILL_FILENAME, config.MODELS_DIR / config.FLUX_FILL_FILENAME),
        (config.FLUX_T5_REPO, config.FLUX_T5_FILENAME, config.TEXT_ENCODERS_DIR / config.FLUX_T5_FILENAME),
        (config.FLUX_CLIP_REPO, config.FLUX_CLIP_FILENAME, config.TEXT_ENCODERS_DIR / config.FLUX_CLIP_FILENAME),
        (config.FLUX_VAE_REPO, config.FLUX_VAE_REMOTE_PATH, config.VAE_DIR / config.FLUX_VAE_FILENAME),
    ):
        if dest.exists():
            print(f"  {dest.name}: already present")
            continue
        print(f"  downloading {dest.name}...")
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(hf_hub_download(repo_id=repo, filename=remote), dest)


def run(flux: bool = False) -> None:
    clone_vendor_repos()
    write_extra_model_paths()
    print("Downloading VAE, text encoder, depth, segmentation and caption models...")
    download_small_weights()
    download_subject_models()
    if flux:
        print("Downloading FLUX.1 Fill, its text encoders and VAE (~14GB)...")
        download_flux_models()
    print("\nSetup complete. Run `soto doctor` to verify the environment.")


if __name__ == "__main__":
    run()
